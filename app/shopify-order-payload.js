export function orderDeliveryPayload(order) {
  return {
    id: order.id,
    admin_graphql_api_id: order.admin_graphql_api_id,
    name: order.name,
    order_number: order.order_number,
    current_total_price: order.current_total_price,
    total_price: order.total_price,
    currency: order.currency,
    presentment_currency: order.presentment_currency,
    created_at: order.created_at,
    financial_status: order.financial_status,
    email: order.email,
    phone: order.phone,
    browser_ip: order.browser_ip,
    order_status_url: order.order_status_url,
    client_details: { user_agent: order.client_details?.user_agent },
    customer: {
      id: order.customer?.id,
      admin_graphql_api_id: order.customer?.admin_graphql_api_id,
      email: order.customer?.email,
      phone: order.customer?.phone,
      first_name: order.customer?.first_name,
      last_name: order.customer?.last_name,
    },
    billing_address: {
      phone: order.billing_address?.phone,
      first_name: order.billing_address?.first_name,
      last_name: order.billing_address?.last_name,
      city: order.billing_address?.city,
      province: order.billing_address?.province,
      zip: order.billing_address?.zip,
      country_code: order.billing_address?.country_code,
    },
    line_items: (order.line_items || []).map((item) => ({
      product_id: item.product_id,
      variant_id: item.variant_id,
      sku: item.sku,
      name: item.name,
      title: item.title,
      price: item.price,
      quantity: item.quantity,
    })),
  };
}
